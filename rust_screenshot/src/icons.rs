// ─────────────── 渲染 + 解析 ───────────────

fn paint(c: [u8; 4]) -> Paint<'static> {
    let mut p = Paint::default();
    p.set_color_rgba8(c[0], c[1], c[2], c[3]);
    p.anti_alias = true;
    p
}

/// 把 24×24 viewBox 的图标路径填充到「以 (cx,cy) 为中心、边长 `box_px`」的方框内。
/// `pre` 在 viewBox 坐标系内先行作用（用于平移/镜像等图标自带的 group transform）。
pub fn render(
    pm: &mut Pixmap,
    paths: &[&str],
    pre: Pre,
    cx: f32,
    cy: f32,
    box_px: f32,
    color: [u8; 4],
) {
    let s = box_px / 24.0;
    let tx0 = cx - box_px / 2.0;
    let ty0 = cy - box_px / 2.0;
    let [sx, ky, kx, sy, tx, ty] = pre;
    // 合成「先 pre，再缩放居中」的仿射矩阵（见 from_row 列序）。
    let tf = Transform::from_row(
        s * sx,
        s * ky,
        s * kx,
        s * sy,
        s * tx + tx0,
        s * ty + ty0,
    );
    let p = paint(color);
    for d in paths {
        if let Some(path) = build(d) {
            pm.fill_path(&path, &p, FillRule::EvenOdd, tf, None);
        }
    }
}

/// 与 [`render`] 相同的定位/缩放，但以「描边」而非「填充」绘制——用于本身就是
/// 线条轮廓的图标（如橡皮擦：本体轮廓 + 分隔线 + 地线均为描边路径）。
/// `stroke_w` 以 24×24 viewBox 为单位给出，会随目标尺寸一并缩放。
